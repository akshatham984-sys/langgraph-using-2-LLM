# 7. LLM FUNCTION
# -----------------------------
def run_llm(prompt, max_new_tokens=350):

    messages = [
        {
            "role": "system",
            "content": "You are a helpful academic assistant. Give clear and factual answers."
        },
        {
            "role": "user",
            "content": prompt
        }
    ]

    output = llm(
        messages,
        max_new_tokens=max_new_tokens,
        do_sample=False
    )

    generated = output[0]["generated_text"]

    if isinstance(generated, list):
        return generated[-1]["content"]

    return generated


