# 4. SPLIT DOCUMENT INTO CHUNKS
# -----------------------------
def create_chunks(text, chunk_size=2500, overlap=300):

    chunks = []

    start = 0

    while start < len(text):

        end = start + chunk_size

        chunk = text[start:end]

        if chunk.strip():
            chunks.append(chunk)

        start = end - overlap

    return chunks


chunks = create_chunks(document_text)

