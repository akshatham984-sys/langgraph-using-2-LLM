# 8. LANGGRAPH STATE
# -----------------------------
class VerificationState(TypedDict):

    document_text: str
    question: str

    retrieved_context: str

    llm1_answer: str

    web_results: str

    llm2_answer: str


# -----------------------------
# 9. LLM 1 NODE
# -----------------------------
def llm1_node(state):

    print("\n")
    print("========================================")
    print("STEP 1: LLM 1 - DOCUMENT ANALYSIS")
    print("========================================")

    question = state["question"]

    relevant_chunks = retrieve_relevant_chunks(
        question,
        top_k=3
    )

    context = "\n\n--- DOCUMENT SECTION ---\n\n".join(
        relevant_chunks
    )

    prompt = f"""
You are LLM 1 in a document verification system.

Use ONLY the document context below.

DOCUMENT CONTEXT:
{context}

QUESTION:
{question}

TASK:
Answer the question using the document.

Explain the answer clearly.
Mention the important points.
Do not invent information.

DOCUMENT-BASED ANSWER:
"""

    answer = run_llm(
        prompt,
        max_new_tokens=400
    )

    print("\nLLM 1 ANSWER:")
    print(answer)

    return {
        "retrieved_context": context,
        "llm1_answer": answer
    }


# -----------------------------
# 10. WEB SEARCH NODE
# -----------------------------
def web_search_node(state):

    print("\n")
    print("========================================")
    print("STEP 2: WEB SEARCH")
    print("========================================")

    question = state["question"]

    llm1_answer = state["llm1_answer"]

    # Create a short web query
    query = question

    print("Searching web for:")
    print(query)

    try:

        from ddgs import DDGS

        search_results = []

        with DDGS() as ddgs:

            results = ddgs.text(
                query,
                max_results=5
            )

            for result in results:

                title = result.get("title", "")
                body = result.get("body", "")
                href = result.get("href", "")

                search_results.append(
                    f"TITLE: {title}\n"
                    f"CONTENT: {body}\n"
                    f"SOURCE: {href}"
                )

        web_text = "\n\n--------------------\n\n".join(
            search_results
        )

        if not web_text:
            web_text = "No web results were found."

    except Exception as e:

        web_text = f"Web search failed: {str(e)}"

    print("\nWEB EVIDENCE:")
    print(web_text[:5000])

    return {
        "web_results": web_text
    }


# -----------------------------
# 11. LLM 2 VERIFICATION NODE
# -----------------------------
def llm2_node(state):

    print("\n")
    print("========================================")
    print("STEP 3: LLM 2 - VERIFICATION")
    print("========================================")

    question = state["question"]

    llm1_answer = state["llm1_answer"]

    web_results = state["web_results"]

    prompt = f"""
You are LLM 2, the final verification agent.

You must verify the answer produced by LLM 1 using the web evidence.

QUESTION:
{question}

--------------------------------
LLM 1 ANSWER
--------------------------------

{llm1_answer}

--------------------------------
WEB EVIDENCE
--------------------------------

{web_results}

--------------------------------
TASK
--------------------------------

Compare the LLM 1 answer with the web evidence.

Determine:

1. What information is supported?
2. What information is not supported?
3. Are there any contradictions?
4. What is the corrected final answer?

Use this format:

VERIFICATION STATUS:
Supported / Partially Supported / Conflicting / Insufficient Evidence

ANALYSIS:
Explain the comparison.

FINAL ANSWER:
Give the most accurate answer based on the document and web evidence.

IMPORTANT:
Do not blindly trust LLM 1.
Do not blindly trust the web.
If evidence is insufficient, clearly say so.
"""

    final_answer = run_llm(
        prompt,
        max_new_tokens=500
    )

    print("\nFINAL VERIFICATION:")
    print(final_answer)

    return {
        "llm2_answer": final_answer
    }


